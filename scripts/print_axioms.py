"""Print the axioms that every theorem of the Lean library depends on.

    python scripts/print_axioms.py              # print the table
    python scripts/print_axioms.py --write      # rewrite docs/axioms.txt
    python scripts/print_axioms.py --check      # fail if docs/axioms.txt is stale,
                                                # or if a theorem uses an axiom outside
                                                # the three standard ones, or sorryAx

The README says each theorem depends only on Lean's three standard axioms
(propext, Classical.choice, Quot.sound). A text search for `sorry` cannot show
that: it misses native_decide, unsafe code and a new `axiom`. This script asks
Lean itself. It writes one scratch file that imports SquigglyLine, walks the
environment for every theorem declared in a SquigglyLine module, and prints
`Lean.collectAxioms` for each. It is one Lean run, not one per theorem.

It needs the library built (`lake build` from lean/), because it imports the
compiled modules. Run it when no other `lake build` is running.

The output file has one line per theorem, sorted by name:

    SquigglyLine.some_theorem: Classical.choice, Quot.sound, propext

An empty list is written as `(none)`. Compiler-made helpers (names with a
`_proof_1`, `match_1` or `eq_1` part) are left out: a user-written theorem that
uses one reports the helper's axioms as its own.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN_DIR = ROOT / "lean"
OUTPUT = ROOT / "docs" / "axioms.txt"
STANDARD = {"propext", "Classical.choice", "Quot.sound"}
START = "AXIOMS-BEGIN"
END = "AXIOMS-END"

HEADER = (
    "# The axioms of every theorem in lean/SquigglyLine, from Lean's `collectAxioms`.\n"
    "# Generated by scripts/print_axioms.py. Do not edit by hand; CI fails when it is stale.\n"
    "# The three standard axioms are propext, Classical.choice and Quot.sound.\n"
)

LEAN_PROGRAM = f"""import SquigglyLine
open Lean

def isOurs (env : Environment) (name : Name) : Bool :=
  match env.getModuleIdxFor? name with
  | some idx => (env.header.moduleNames[idx.toNat]!).getRoot == `SquigglyLine
  | none => false

def isHelper (name : Name) : Bool :=
  name.isInternalDetail || name.isInaccessibleUserName

run_cmd Elab.Command.liftCoreM do
  let env ← getEnv
  let mut rows : Array String := #[]
  for (name, info) in env.constants.map₁.toList do
    match info with
    | .thmInfo _ =>
      if isOurs env name && !isHelper name then
        let axioms ← collectAxioms name
        let names := (axioms.map toString).qsort (· < ·)
        let text := if names.isEmpty then "(none)" else ", ".intercalate names.toList
        rows := rows.push s!"{{name}}: {{text}}"
    | _ => pure ()
  IO.println "{START}"
  for row in rows.qsort (· < ·) do
    IO.println row
  IO.println "{END}"
"""


def run_lean() -> list[str]:
    with tempfile.TemporaryDirectory() as folder:
        scratch = Path(folder) / "PrintAxioms.lean"
        scratch.write_text(LEAN_PROGRAM, encoding="utf-8", newline="\n")
        result = subprocess.run(
            ["lake", "env", "lean", str(scratch)],
            cwd=LEAN_DIR,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
    lines = result.stdout.splitlines()
    if START not in lines or END not in lines:
        sys.stderr.write(result.stdout[-3000:] + result.stderr[-3000:])
        raise SystemExit("Lean did not print the table (is the library built? run `lake build` in lean/)")
    return [line for line in lines[lines.index(START) + 1 : lines.index(END)] if line.strip()]


def problems(rows: list[str]) -> list[str]:
    found = []
    for row in rows:
        name, _, axioms = row.partition(": ")
        if axioms == "(none)":
            continue
        extra = {axiom.strip() for axiom in axioms.split(",")} - STANDARD
        if extra:
            found.append(f"{name} uses {', '.join(sorted(extra))}")
    return found


def render(rows: list[str]) -> str:
    return HEADER + "\n".join(rows) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="rewrite docs/axioms.txt")
    parser.add_argument("--check", action="store_true", help="fail if the file is stale or an axiom is not standard")
    args = parser.parse_args()
    rows = run_lean()
    text = render(rows)
    bad = problems(rows)
    if args.write:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(rows)} theorems")
    elif not args.check:
        sys.stdout.write(text)
    summary: dict[str, int] = {}
    for row in rows:
        summary[row.partition(": ")[2]] = summary.get(row.partition(": ")[2], 0) + 1
    print(f"\n{len(rows)} theorems; {len(bad)} with an axiom outside the three", file=sys.stderr)
    for axioms, count in sorted(summary.items(), key=lambda item: -item[1]):
        print(f"  {count:5d}  {axioms}", file=sys.stderr)
    for line in bad:
        print(f"  PROBLEM: {line}", file=sys.stderr)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUTPUT.exists() else ""
        if current != text:
            print("docs/axioms.txt is out of date: run `python scripts/print_axioms.py --write`", file=sys.stderr)
            return 1
    return 1 if bad and args.check else 0


if __name__ == "__main__":
    raise SystemExit(main())
